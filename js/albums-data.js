/* B 站视频嵌入与搜索地址生成（BV 号或 av 号皆可） */
window.biliEmbed = function (id) {
  var base = "https://player.bilibili.com/player.html?";
  if (/^BV/i.test(String(id || ""))) {
    return base + "bvid=" + id + "&high_quality=1&danmaku=0";
  }
  return base + "aid=" + String(id || "").replace(/^av/i, "") + "&high_quality=1&danmaku=0";
};

window.biliSearch = function (query) {
  return "https://search.bilibili.com/all?keyword=" + encodeURIComponent(query);
};
